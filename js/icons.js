/**
 * icon("clock") → an <svg> string. `cls` lands on the element so a caller can
 * size or colour one without a wrapper.
 */
export function icon(name, cls = "") {
  const body = ALL[name];
  if (!body) return "";
  return `<svg class="ico${cls ? " " + cls : ""}" viewBox="0 0 24 24" fill="none" stroke="currentColor" `
    + `stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}

